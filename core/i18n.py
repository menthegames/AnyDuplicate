"""
Модуль локализации (i18n) AnyDuplicate Advanced
Поддерживает русский и английский языки.
"""
from core.config_manager import ConfigManager

# Глобальный экземпляр конфига (устанавливается при инициализации)
_config = None

def init_i18n(config=None):
    """Инициализирует модуль i18n с переданным конфигом."""
    global _config
    if config is not None:
        _config = config
    elif _config is None:
        _config = ConfigManager()

def get_current_language() -> str:
    """Возвращает текущий язык из конфига."""
    global _config
    if _config is None:
        init_i18n()
    return _config.get("language", "ru") if _config else "ru"

def tr(key: str, default: str = None) -> str:
    """
    Возвращает перевод для указанного ключа на текущем языке.
    Если перевод не найден, возвращает default или сам ключ.
    """
    lang = get_current_language()
    translations = TRANSLATIONS.get(lang, TRANSLATIONS.get("ru", {}))
    result = translations.get(key)
    if result is not None:
        return result
    # Fallback: попробовать русский
    ru_result = TRANSLATIONS.get("ru", {}).get(key)
    if ru_result is not None:
        return ru_result
    return default if default is not None else key

